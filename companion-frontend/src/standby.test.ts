import { describe, expect, it } from 'vitest'
import { STANDBY_IDLE_MS, StandbySchedule, standbyLibraryOptions, standbyMotion, standbyMotionIds } from './standby'

describe('standby timing', () => {
  it('starts at exactly 60 seconds with a face still present', () => {
    const schedule = new StandbySchedule(0, () => 0)
    schedule.observeFace(true, 0)
    expect(schedule.tick(59_999, true, false)).toBeUndefined()
    expect(schedule.tick(60_000, true, false)).toBe('sleep')
  })
  it('starts after ten continuous seconds without a detected face, including initial absence', () => {
    const schedule = new StandbySchedule(0)
    schedule.observeFace(false, 100)
    schedule.observeFace(false, 5_000)
    expect(schedule.tick(10_099, true, false)).toBeUndefined()
    expect(schedule.tick(10_100, true, false)).toBeDefined()
  })
  it('face return clears absence and stops standby without resetting every visible frame', () => {
    const schedule = new StandbySchedule(0)
    schedule.observeFace(false, 0)
    schedule.tick(10_000, true, false)
    expect(schedule.observeFace(true, 11_000)).toBe(true)
    expect(schedule.active).toBe(false)
    schedule.observeFace(true, 55_000)
    expect(schedule.tick(70_999, true, false)).toBeUndefined()
    expect(schedule.tick(71_000, true, false)).toBeDefined()
  })
  it('brief misses do not accumulate and camera failures are unknown', () => {
    const schedule = new StandbySchedule(0)
    schedule.observeFace(false, 0)
    schedule.observeFace(true, 9_000)
    schedule.observeFace(false, 9_100)
    expect(schedule.tick(19_099, true, false)).toBeUndefined()
    schedule.observeFace(null, 19_100)
    expect(schedule.tick(30_000, true, false)).toBeUndefined()
  })
  it('interaction cancels standby and restarts the absence window', () => {
    const schedule = new StandbySchedule(0)
    schedule.observeFace(false, 0)
    schedule.tick(10_000, true, false)
    schedule.interaction(11_000)
    expect(schedule.active).toBe(false)
    expect(schedule.tick(20_999, true, false)).toBeUndefined()
    expect(schedule.tick(21_000, true, false)).toBeDefined()
  })
  it.each(['hidden', 'reply', 'call'])('does not lose the timer when blocked by %s', reason => {
    const schedule = new StandbySchedule(0)
    expect(schedule.tick(60_000, reason !== 'hidden', reason !== 'hidden')).toBeUndefined()
    expect(schedule.tick(90_000, true, false)).toBeUndefined()
    expect(schedule.tick(149_999, true, false)).toBeUndefined()
    expect(schedule.tick(150_000, true, false)).toBeDefined()
  })
  it('plays one action, then a natural-idle interval, then another random action', () => {
    const schedule = new StandbySchedule(0, () => 0)
    expect(schedule.tick(60_000, true, false)).toBe('sleep')
    expect(schedule.finish('cloud_standby_sleep', 68_000)).toBe(true)
    expect(schedule.tick(68_000 + STANDBY_IDLE_MS - 1, true, false)).toBeUndefined()
    expect(schedule.tick(76_000, true, false)).toBe('sing')
    expect(schedule.finish('cloud_standby_sing', 84_000)).toBe(true)
    expect(schedule.tick(91_999, true, false)).toBeUndefined()
    expect(schedule.tick(92_000, true, false)).toBe('sleep')
  })
  it('falls back to natural idle for a missing completion, never repeats the action', () => {
    const schedule = new StandbySchedule(0, () => .8)
    expect(schedule.tick(60_000, true, false)).toBe('stretch')
    expect(schedule.tick(71_999, true, false)).toBeUndefined()
    expect(schedule.tick(72_000, true, false)).toBe('idle')
    expect(schedule.tick(79_999, true, false)).toBeUndefined()
    expect(schedule.tick(80_000, true, false)).toBe('look_around')
  })
  it('ignores old or unrelated completions after interaction and while resting', () => {
    const schedule = new StandbySchedule(0, () => 0)
    schedule.tick(60_000, true, false)
    expect(schedule.finish('cloud_wave', 61_000)).toBe(false)
    schedule.interaction(61_000)
    expect(schedule.finish('cloud_standby_sleep', 68_000)).toBe(false)
    expect(schedule.active).toBe(false)
    expect(schedule.tick(120_999, true, false)).toBeUndefined()
    expect(schedule.tick(121_000, true, false)).toBe('sing')
    expect(schedule.finish('cloud_standby_sing', 129_000)).toBe(true)
    expect(schedule.finish('cloud_standby_sing', 130_000)).toBe(false)
  })
  it('cancels the natural-idle interval when the pet is busy or standby is disabled', () => {
    const schedule = new StandbySchedule(0)
    const id = schedule.tick(60_000, true, false)
    schedule.finish(`cloud_standby_${id}`, 68_000)
    expect(schedule.tick(70_000, false, false)).toBeUndefined()
    expect(schedule.active).toBe(false)
    expect(schedule.tick(80_000, true, false)).toBeUndefined()
    expect(schedule.tick(139_999, true, false)).toBeUndefined()
    expect(schedule.tick(140_000, true, false)).toBeDefined()
  })
  it('lists natural idle first and uses one-shot motion only for automatic playback', () => {
    expect(standbyLibraryOptions[0]).toEqual({ value: 'gesture:idle', label: '自然待机', group: '待机动作' })
    expect(standbyMotion('stretch', false).loop).toBe(false)
    expect(standbyMotion('stretch').loop).toBe(true)
  })
  it('uses six independent cloud archives, not reply emotions', () => {
    expect(new Set(standbyMotionIds.map(id => standbyMotion(id).id)).size).toBe(6)
    for (const id of standbyMotionIds) {
      const motion = standbyMotion(id)
      expect(motion.url).toBe(`/api/motion/library/cloud_standby_${id}`)
      expect(motion.loop).toBe(true)
    }
  })
})
